const SLUG_ALIAS: Record<string, string> = {
  "large-billboard": "large-billboard-building",
  "advertisement-on-the-fence": "advertisement-fence",
};

function resolveRuCopy(slug: string): RussianServiceCopy | undefined {
  const canonical = SLUG_ALIAS[slug] ?? slug;
  return RU_SERVICE_COPY[canonical];
}

export function localizePublicServices(
  services: PublicServiceItem[],
  locale: Locale
): PublicServiceCopyResult[] {
  if (locale !== "ru") return services;

  return services.map((service) => {
    const copy = resolveRuCopy(service.slug);
    if (!copy) return service;

    // Only replace with default Russian catalog copy if the DB row still carries
    // its default English title (preserving any custom title edited by an admin).
    const isDefaultEnglish = copy.defaultEnglishTitles.some(
      (eng) => eng.toLowerCase() === service.title.trim().toLowerCase()
    );
    if (!isDefaultEnglish) return service;

    return {
      ...service,
      name: copy.title,
      title: copy.title,
      description: copy.shortDesc,
      shortDesc: copy.shortDesc,
    };
  });
}

type PublicServiceCopyResult = PublicServiceItem;

export function localizeCatalogService(
  service: CatalogServiceItem,
  locale: Locale
): CatalogServiceItem {
  if (locale !== "ru") return service;

  const copy = resolveRuCopy(service.slug);
  if (!copy) return service;

  const isDefaultEnglish = copy.defaultEnglishTitles.some(
    (eng) => eng.toLowerCase() === service.title.trim().toLowerCase()
  );
  if (!isDefaultEnglish) return service;

  return {
    ...service,
    title: copy.title,
    shortDesc: copy.shortDesc,
    fullDesc: copy.fullDesc,
    includes: copy.includes,
    shapesIntroduction: copy.shapesIntroduction,
    shapes: copy.shapes,
    resultText: copy.resultText,
  };
}
